#[tokio::test]
async fn below_threshold_fails() {
    let (signers, pkp, params) = build_group(3, 5);
    let participants: Vec<_> = signers.keys().copied().take(2).collect(); // only 2, need 3
    let transport = LocalTransport::new(signers);
    let coord = Coordinator::new(params, pkp);
    let mut rng = OsRng;
    let result = coord
        .sign(&transport, b"x", &participants, &mut rng)
        .await;
    assert!(result.is_err(), "expected below-threshold failure");
}

#[tokio::test]
async fn duplicate_participant_fails() {
    let (signers, pkp, params) = build_group(2, 3);
    let mut participants: Vec<_> = signers.keys().copied().take(2).collect();
    participants.push(participants[0]);
    let transport = LocalTransport::new(signers);
    let coord = Coordinator::new(params, pkp);
    let mut rng = OsRng;
    let result = coord
        .sign(&transport, b"x", &participants, &mut rng)
        .await;
    assert!(result.is_err(), "expected duplicate participant failure");
}

#[tokio::test]
async fn unknown_participant_fails() {
    let (signers, pkp, params) = build_group(2, 3);
    let participants: Vec<_> = {
        let mut ids: Vec<_> = signers.keys().copied().take(1).collect();
        // 4 is outside the 1..=3 identifier range generated by the trusted dealer.
        ids.push(frost_core::Identifier::<Cs>::try_from(4u16).unwrap());
        ids
    };
    let transport = LocalTransport::new(signers);
    let coord = Coordinator::new(params, pkp);
    let mut rng = OsRng;
    let result = coord
        .sign(&transport, b"x", &participants, &mut rng)
        .await;
    assert!(result.is_err(), "expected unknown participant failure");
}
